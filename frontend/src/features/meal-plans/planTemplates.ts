export function applyTemplateToDescription(
  template: PlanDescriptionTemplate,
  base: PlanDescriptionSchema,
  today = new Date(),
): PlanDescriptionSchema {
  const nextReviewDate = new Date(today.getTime() + template.reviewIntervalDays * 24 * 60 * 60 * 1000)
  return {
    ...base,
    templateSlug: template.slug,
    sections: {
      ...base.sections,
      interventionGoal: template.goal,
      rationale: template.rationale,
      dietaryPrinciples: template.dietaryPrinciples,
      clientRecommendations: template.clientRecommendations,
      monitoringPlan: template.monitoringPlan,
      followUpRequirements: [...template.followUpRequirements],
      nextReviewDate: nextReviewDate.toISOString().slice(0, 10),
      communicationTone: template.tone,
    },
  }
}
